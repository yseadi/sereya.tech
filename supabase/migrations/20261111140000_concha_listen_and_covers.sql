-- Concha's universe, more than geopolitics:
--  * "listen" words: specific words Yasmim wants Concha to bring from the sources (strong pull, one category each).
--  * "category" words: the words that place an item in a category, now editable (seeded with the old built-in list).
--  * Glossary cards get a cover photo (image_url). Cards that already had a picture in their text use it.
-- Safe to run more than once.

alter table public.concha_terms drop constraint if exists concha_terms_kind_check;
alter table public.concha_terms add constraint concha_terms_kind_check
  check (kind in ('glossary', 'never', 'listen', 'category'));
alter table public.concha_terms drop constraint if exists concha_terms_category_needed;
alter table public.concha_terms add constraint concha_terms_category_needed
  check (kind not in ('listen', 'category') or category is not null);

alter table public.concha_terms add column if not exists image_url text not null default ''
  check (image_url = '' or image_url ~ '^(https?://|/)' and char_length(image_url) <= 1000);
comment on column public.concha_terms.image_url is 'Cover photo of a public Glossary card.';

update public.concha_terms
   set image_url = substring(definition from '!\[[^\]\n]*\]\(((?:https://|/)[^)\s]+)\)')
 where kind = 'glossary' and image_url = ''
   and definition ~ '!\[[^\]\n]*\]\(((?:https://|/)[^)\s]+)\)';

